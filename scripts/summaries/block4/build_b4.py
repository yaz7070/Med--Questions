"""Build the Block 4 weekly study guides (week-13/14/15-summary.html).

Content lives in w13.py, w14.py, w15.py (written from the lecture slides and
Nicole's Notes). Nicole's original cards (cards.json, from convert.py) sit in a
drawer at the end of each tab so her exact wording stays one tap away.
Run: python3 scripts/summaries/block4/build_b4.py
"""
import html
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
import kit  # noqa: E402
import w13, w14, w15  # noqa: E402

SITE = pathlib.Path("/home/claude/med-notes/quartz/static/pages")
CARDS = json.loads((HERE / "cards.json").read_text())
WEEKS = {13: w13, 14: w14, 15: w15}

JS = """
(function(){
  const tabs=[...document.querySelectorAll('.tabs [role="tab"]')], panels=[...document.querySelectorAll('.panel')];
  const KEY="differential-b4-tab-"+document.body.dataset.w, q=document.getElementById("q"), count=document.getElementById("count");
  function show(t,focus){ tabs.forEach(x=>{ const on=x===t; x.setAttribute("aria-selected",on); x.tabIndex=on?0:-1;
    document.getElementById(x.getAttribute("aria-controls")).hidden=!on; }); if(focus) t.focus(); t.scrollIntoView({block:"nearest",inline:"nearest"}); try{ localStorage.setItem(KEY,t.id); }catch(e){} }
  tabs.forEach((t,i)=>{ t.onclick=()=>{ q.value=""; search(); show(t); window.scrollTo({top:0}); };
    t.onkeydown=e=>{ const d=e.key==="ArrowRight"?1:e.key==="ArrowLeft"?-1:0; if(d){ e.preventDefault(); show(tabs[(i+d+tabs.length)%tabs.length],true); } }; });
  try{ const s=document.getElementById(localStorage.getItem(KEY)); if(s && tabs.includes(s)) show(s); }catch(e){}
  document.querySelectorAll(".qa button").forEach(b=>{ b.onclick=()=>{ const a=b.nextElementSibling, open=a.hidden; a.hidden=!open; b.setAttribute("aria-expanded",open); }; });
  const items=[...document.querySelectorAll(".topic,.ncard")];
  items.forEach(x=>x.dataset.text=x.textContent.toLowerCase().replace(/\\s+/g," "));
  function search(){
    const s=q.value.trim().toLowerCase();
    if(!s){ document.body.classList.remove("searching"); items.forEach(c=>c.classList.remove("hidden"));
      document.querySelectorAll(".phead,details.nn").forEach(x=>x.classList.remove("hidden")); count.textContent="";
      const cur=tabs.find(t=>t.getAttribute("aria-selected")==="true")||tabs[0]; show(cur); return; }
    document.body.classList.add("searching"); let n=0;
    items.forEach(c=>{ const hit=c.dataset.text.includes(s); c.classList.toggle("hidden",!hit); if(hit) n++; });
    document.querySelectorAll("details.nn").forEach(d=>{ const any=d.querySelector(".ncard:not(.hidden)"); d.classList.toggle("hidden",!any); if(any) d.open=true; });
    panels.forEach(p=>p.querySelector(".phead").classList.toggle("hidden",!p.querySelector(".topic:not(.hidden),.ncard:not(.hidden)")));
    count.textContent=n?`${n} match${n===1?"":"es"}`:"No matches";
  }
  q.addEventListener("input",search);
  document.querySelectorAll(".toc a").forEach(a=>a.onclick=e=>{ e.preventDefault(); document.querySelector(a.getAttribute("href")).scrollIntoView({behavior:matchMedia("(prefers-reduced-motion: reduce)").matches?"auto":"smooth"}); });
})();
"""

THEME = """(function(){const r=document.documentElement;function theme(){let t=null;try{t=localStorage.getItem("theme");}catch(e){}
r.dataset.theme=t||(matchMedia("(prefers-color-scheme: dark)").matches?"dark":"light");}theme();addEventListener("storage",theme);})();"""


def ncard(i):
    c = CARDS[i]
    body = c["html"].replace("FIGDIR", "b4figs")
    body = body.replace("<th><b>COVID-19 Vaccine Hesitancy Factor</b></th><th></th>", "<th><b>COVID-19 Vaccine Hesitancy Factor</b></th><th><b>Reasoning</b></th>")
    body = re.sub(r'<figure><img src="([^"]+)"([^>]*)></figure>', r'<figure><a href="\1" target="_blank" rel="noopener"><img src="\1"\2></a><figcaption>Tap to enlarge</figcaption></figure>', body)
    return f'<div class="ncard"><h4>{html.escape(c["heading"].rstrip(":"))}<span class="src">p. {c["page"]}</span></h4>{body}</div>'


def render(w, mod):
    tabs = mod.TABS
    o = ['<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">',
         f"<title>Week {w} Study Guide</title>",
         '<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible+Next:wght@400;700&display=swap">',
         "<!-- Generated by scripts/summaries/block4/build_b4.py. Edit w13.py, w14.py, w15.py or kit.py, not this file. -->",
         f"<style>{kit.CSS}</style></head><body data-w=\"{w}\">", f"<script>{THEME}</script>", '<div class="wrap">',
         f'<header><h1>{mod.TITLE}</h1><p class="lede">{mod.LEDE}</p>'
         '<div class="legend"><span><b>Highlighted</b> = bold in Nicole\'s Notes</span><span>Each tab ends with a quick self-test.</span></div>'
         '<details class="lectures"><summary>Lectures this week</summary><ul>' + "".join(f"<li>{html.escape(l)}</li>" for l in mod.LECTURES) + "</ul></details></header>",
         '<div class="bar"><div class="search"><input id="q" type="search" placeholder="Search this week, e.g. qSOFA or acyclovir" aria-label="Search this week"><span class="count" id="count" aria-live="polite"></span></div>',
         '<div class="tabs" role="tablist" aria-label="Topics">' + "".join(
             f'<button role="tab" id="t-{t["key"]}" aria-controls="p-{t["key"]}" aria-selected="{str(i == 0).lower()}"{"" if i == 0 else " tabindex=\"-1\""}>{html.escape(t["label"])}</button>'
             for i, t in enumerate(tabs)) + "</div></div>"]
    for i, t in enumerate(tabs):
        k = t["key"]
        topics = [x.replace("{tab}", k) for x in t["topics"]]
        toc = "".join(f'<li><a href="#{m.group(1)}">{html.escape(html.unescape(m.group(2)))}</a></li>'
                      for m in (re.search(r'id="([^"]+)" data-title="([^"]+)"', x) for x in topics))
        o.append(f'<section class="panel" id="p-{k}" role="tabpanel" aria-labelledby="t-{k}"{"" if i == 0 else " hidden"}>')
        o.append(f'<div class="phead"><h2>{html.escape(t["label"])}</h2><p class="plede">{t["lede"]}</p><ul class="toc">{toc}</ul></div>')
        o += topics
        if False and t.get("notes"):  # Nicole's original-notes drawer removed at the student's request
            o.append(f'<details class="nn"><summary><span>Nicole\'s Notes, original wording <span class="sub">{len(t["notes"])} section{"s" if len(t["notes"]) > 1 else ""}</span></span></summary><div class="nnbody">'
                     + "".join(ncard(n) for n in t["notes"]) + "</div></details>")
        if t.get("recall"):
            o.append('<div class="recall"><h3>Quick recall</h3><p class="hint">Answer in your head, then check.</p>' + "".join(
                f'<div class="qa"><button aria-expanded="false">{html.escape(a)}</button><p class="ans" hidden>{html.escape(b)}</p></div>' for a, b in t["recall"]) + "</div>")
        o.append("</section>")
    o.append(f"</div><script>{JS}</script></body></html>\n")
    return "\n".join(o)


if __name__ == "__main__":
    used = set()
    for w, mod in WEEKS.items():
        (SITE / f"week-{w}-summary.html").write_text(render(w, mod))
        for t in mod.TABS:
            used |= set(t.get("notes", []))
        print("wrote", f"week-{w}-summary.html", "tabs:", len(mod.TABS), "topics:", sum(len(t["topics"]) for t in mod.TABS))

